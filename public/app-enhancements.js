const renderProductsWithoutFavoriteState = renderProducts;
renderProducts = function () {
  renderProductsWithoutFavoriteState();
  document.querySelectorAll("#productGrid .product-card").forEach((card) => {
    const product = products.find((item) => localizedProduct(item).name === card.querySelector("h3")?.textContent);
    if (product) card.querySelector(".price-row strong").textContent = formatPrice(product.price);
    if (product?.name === "Икра горбуши 0.5 кг") {
      card.querySelector(".product-image").style.backgroundPosition = "center 78%";
    }
    if (product?.name === "Филе судака" || product?.name === "Филе судака без глазури") {
      card.querySelector(".product-image").style.backgroundPosition = "center 78%";
    }
  });
  const toggle = byId("favoritesToggle");
  if (toggle) {
    toggle.setAttribute("aria-pressed", String(state.favoritesOnly));
    byId("favoritesToggleLabel").textContent = state.favoritesOnly ? t("allProducts") : `♡ ${t("favorites")}`;
    byId("favoritesCount").textContent = String(state.favorites.length);
  }
  if (state.favoritesOnly) byId("resultsTitle").textContent = t("favorites");
  document.querySelectorAll("#productGrid .product-card").forEach((card) => {
    const product = products.find((item) => localizedProduct(item).name === card.querySelector("h3")?.textContent);
    const button = card.querySelector(".favorite");
    if (!product || !button) return;
    const active = state.favorites.includes(product.id);
    button.dataset.productId = String(product.id);
    button.textContent = active ? "♥" : "♡";
    button.classList.toggle("active", active);
    button.setAttribute("aria-pressed", String(active));
    button.setAttribute("aria-label", t(active ? "favoriteRemove" : "favoriteAdd"));
    button.title = t(active ? "favoriteRemove" : "favoriteAdd");
    button.onclick = (event) => {
      event.stopPropagation();
      state.favorites = state.favorites.includes(product.id)
        ? state.favorites.filter((id) => id !== product.id)
        : [...state.favorites, product.id];
      save();
      renderProducts();
    };
  });
};

