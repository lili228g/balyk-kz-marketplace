function authServerMessage(message, mode) {
  const normalized = String(message || "").toLowerCase();
  if (normalized.includes("никнейм") && (normalized.includes("занят") || normalized.includes("уже"))) return { text: t("nicknameTakenError"), fields: ["name"] };
  if (normalized.includes("email") && normalized.includes("уже")) return { text: t("emailTakenError"), fields: ["email"] };
  if (normalized.includes("телефон") && normalized.includes("уже")) return { text: t("phoneTakenError"), fields: ["phone"] };
  if (mode === "login") return { text: t("loginInvalidError"), fields: ["email", "password"] };
  if (normalized.includes("email")) return { text: t("emailError"), fields: ["email"] };
  if (normalized.includes("телефон")) return { text: t("checkoutPhoneError"), fields: ["phone"] };
  if (normalized.includes("парол")) return { text: t("passwordError"), fields: ["password"] };
  return { text: message, fields: [] };
}

