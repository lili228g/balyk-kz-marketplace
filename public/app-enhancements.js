function normalizePhone(value) {
  let digits = String(value || "").replace(/\D/g, "");
  if (digits.length === 10) digits = `7${digits}`;
  else if (digits.length === 11 && digits.startsWith("8")) digits = `7${digits.slice(1)}`;
  return digits;
}

function validEmail(value) {
  return /^[A-Z0-9.!#$%&'*+/=?^_`{|}~-]+@(?:[A-Z0-9](?:[A-Z0-9-]{0,61}[A-Z0-9])?\.)+[A-Z]{2,}$/i.test(String(value || "").trim());
}

function validKzPhone(value) {
  const input = String(value || "").trim();
  if (!/^\+?[\d\s().-]+$/.test(input)) return false;
  const digits = input.replace(/\D/g, "");
  if (input.startsWith("+")) return digits.length === 11 && digits.startsWith("7");
  return (digits.length === 10 && digits.startsWith("7")) ||
    (digits.length === 11 && (digits.startsWith("7") || digits.startsWith("8")));
}

function authProblems(data, mode) {
  const problems = [];
  const add = (field, message) => problems.push({ field, message });
  if (mode === "register") {
    if (String(data.name || "").trim().length < 2) add("name", state.lang === "en" ? "Enter your name." : state.lang === "kk" ? "Атыңызды енгізіңіз." : "Введите имя минимум из 2 символов.");
    if (!validEmail(data.email)) add("email", t("emailError"));
    if (!validKzPhone(data.phone)) add("phone", t("checkoutPhoneError"));
    if (data.password.length < 8 || !/[A-ZА-ЯӘӨҰҮҚҒІ]/.test(data.password) || !/[a-zа-яәөұүқғі]/.test(data.password) || !/\d/.test(data.password)) add("password", t("passwordError"));
    if (data.password !== data.confirmPassword) add("confirmPassword", t("passwordMismatchError"));
  } else {
    if (!validEmail(data.email)) add("email", t("loginIdentifierError"));
    if (!String(data.password || "")) add("password", t("loginPasswordError"));
  }
  return problems;
}

